// The function registry (ticket 15c): config/functions.json lists every function the workflow
// runs, by kind, each with the id the logs use (gate:<check>, hook:<script>, role:<role>,
// substream:<repo>, skill:<name>). It is generated from the repo, never written by hand:
// - gate: each folder under gates/ (but lib and canary, which are not gates), each check a
//   project's roles run (projects/*/project.json), which is the name a gate record carries, and
//   each stage of the self-gate, as self-gate-<stage> (ticket 31);
// - hook: each hook script the role sessions run under (dispatcher/coder.ts hookSettings);
// - role: each role whose skill exists (the reviewer's skill is review, the planner's the
//   controller's, the learner's learn), so a role arrives with its skill;
// - substream: each repo the upstream watcher reads (watchlist.yaml), and repo discovery when
//   watchlist.yaml has its discover block (ticket 45);
// - skill: each skills/<name>/SKILL.md.
// `node scripts/functions.ts` checks the committed file against the repo (exit 1 when stale);
// `--write` regenerates it. What is read from this repo (its hook settings, project configs and
// watchlist) is in functions-sources.ts (ticket 83), so the registry travels in the runner.

export const KINDS = ['gate', 'hook', 'role', 'substream', 'skill'] as const;
export type FunctionKind = (typeof KINDS)[number];

export interface WorkflowFunction {
  id: string;
  kind: FunctionKind;
  name: string;
  /** Where it lives in the repo. */
  source: string;
}

export interface RegistrySources {
  gateDirs: string[];
  checks: string[];
  hooks: string[];
  skills: string[];
  substreams: string[];
  /** The self-gate's stages; each logs as the gate self-gate-<stage> (ticket 31). */
  selfGate?: string[];
}

export interface RegistryIo {
  /** The folders directly inside a repo folder; [] when it does not exist. */
  dirs(dir: string): string[];
  /** A repo file's text, or undefined when it does not exist. */
  read(path: string): string | undefined;
}

/** Each role and the skill it runs with. */
export const ROLE_SKILLS: Record<string, string> = {
  specifier: 'specifier',
  coder: 'coder',
  cleaner: 'cleaner',
  hardener: 'hardener',
  reviewer: 'review',
  skeptic: 'skeptic',
  walker: 'walker',
  planner: 'controller',
  learner: 'learn',
  evaluator: 'evaluator',
  improver: 'improver',
  researcher: 'researcher',
};

const NOT_GATES = ['lib', 'canary'];
const CHECKS_SOURCE = 'projects/*/project.json checks';
const SELF_GATE_SOURCE = 'scripts/self-gate.ts';
const HOOK_SCRIPT = /adapters\/claude-code\/([\w-]+)\.ts/;

const sorted = (names: Iterable<string>) => [...new Set(names)].sort();

type Settings = { hooks: Record<string, { hooks: { command: string }[] }[]> };

/** The hook scripts the settings run, by name, each once, in order. */
export function hookScripts(settings: Settings): string[] {
  const commands = Object.values(settings.hooks).flatMap((entries) => entries.flatMap((e) => e.hooks.map((h) => h.command)));
  return [...new Set(commands.flatMap((c) => HOOK_SCRIPT.exec(c)?.slice(1) ?? []))];
}

const fn = (kind: FunctionKind, name: string, source: string): WorkflowFunction => ({ id: `${kind}:${name}`, kind, name, source });

export function registryOf(s: RegistrySources): WorkflowFunction[] {
  const dirs = s.gateDirs.filter((d) => !NOT_GATES.includes(d));
  const roles = sorted(Object.keys(ROLE_SKILLS).filter((r) => s.skills.includes(ROLE_SKILLS[r])));
  const gateSources = new Map<string, string>([
    ...s.checks.map((c): [string, string] => [c, CHECKS_SOURCE]),
    ...(s.selfGate ?? []).map((stage): [string, string] => [`self-gate-${stage}`, SELF_GATE_SOURCE]),
    ...dirs.map((d): [string, string] => [d, `gates/${d}`]),
  ]);
  return [
    ...sorted(gateSources.keys()).map((g) => fn('gate', g, gateSources.get(g) as string)),
    ...sorted(s.hooks).map((h) => fn('hook', h, `adapters/claude-code/${h}.ts`)),
    ...roles.map((r) => fn('role', r, `skills/${ROLE_SKILLS[r]}/SKILL.md`)),
    ...sorted(s.substreams).map((r) => fn('substream', r, 'watchlist.yaml')),
    ...sorted(s.skills).map((k) => fn('skill', k, `skills/${k}/SKILL.md`)),
  ];
}

const COMMENT = 'Generated by node scripts/functions.ts --write from the repo (ticket 15c); node scripts/functions.ts checks it. Do not edit by hand.';

export const registryText = (functions: WorkflowFunction[]) => `${JSON.stringify({ $comment: COMMENT, functions }, null, 2)}\n`;

const isFunction = (f: unknown) => {
  const r = Object(f) as Record<string, unknown>;
  return ['id', 'name', 'source'].every((k) => typeof r[k] === 'string') && KINDS.includes(r.kind as FunctionKind);
};

/** The registry's functions; throws on a file that is not one. */
export function parseRegistry(text: string): WorkflowFunction[] {
  let functions: unknown;
  try {
    functions = (JSON.parse(text) as { functions?: unknown }).functions;
  } catch {}
  if (!Array.isArray(functions) || !functions.every(isFunction)) throw new Error('config/functions.json is not a function registry');
  return functions as WorkflowFunction[];
}

/** The registry's ids, or null when it is missing or not a registry. */
function idsOf(text: string | undefined): string[] | null {
  try {
    return parseRegistry(text as string).map((f) => f.id);
  } catch {
    return null;
  }
}

/** What differs between the committed registry and the generated one, in words. */
function staleness(committed: string | undefined, generated: string): string {
  const now = idsOf(generated) as string[];
  const was = idsOf(committed);
  if (was === null) return 'missing: every function';
  const parts = [
    ['missing', now.filter((id) => !was.includes(id))],
    ['not run any more', was.filter((id) => !now.includes(id))],
  ].filter(([, ids]) => ids.length > 0);
  return parts.length === 0 ? 'changed' : parts.map(([what, ids]) => `${what}: ${(ids as string[]).join(', ')}`).join('; ');
}

/** What scripts/functions prints: the check (exit 1 when stale) or, with write, the text to write. */
export function functionsReport(committed: string | undefined, generated: string, write: boolean) {
  const count = (idsOf(generated) as string[]).length;
  if (write) return { stdout: `config/functions.json written: ${count} functions.\n`, stderr: '', exitCode: 0, write: generated };
  if (committed === generated) return { stdout: `config/functions.json is current: ${count} functions.\n`, stderr: '', exitCode: 0, write: undefined };
  return { stdout: '', stderr: `config/functions.json is stale (${staleness(committed, generated)}). Run node scripts/functions.ts --write and commit it.\n`, exitCode: 1, write: undefined };
}
