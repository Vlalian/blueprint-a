import { describe, expect, it } from 'vitest';
import { functionsReport, hookScripts, parseRegistry, registryOf, registryText, type RegistrySources, type WorkflowFunction } from './functions-core.ts';

const SOURCES: RegistrySources = {
  gateDirs: ['onkel', 'lib', 'canary', 'secret-scan'],
  checks: ['lint', 'onkel', 'test'],
  hooks: ['pre-tool', 'observe'],
  skills: ['coder', 'review', 'grill', 'evaluator'],
  substreams: ['affaan-m/ECC'],
};

describe('registryOf: every function the workflow runs, by kind, each with the id the logs use', () => {
  it('lists gates (gate folders and project checks, once each), hooks, roles with a skill, substreams and skills', () => {
    expect(registryOf(SOURCES)).toEqual<WorkflowFunction[]>([
      { id: 'gate:lint', kind: 'gate', name: 'lint', source: 'projects/*/project.json checks' },
      { id: 'gate:onkel', kind: 'gate', name: 'onkel', source: 'gates/onkel' },
      { id: 'gate:secret-scan', kind: 'gate', name: 'secret-scan', source: 'gates/secret-scan' },
      { id: 'gate:test', kind: 'gate', name: 'test', source: 'projects/*/project.json checks' },
      { id: 'hook:observe', kind: 'hook', name: 'observe', source: 'adapters/claude-code/observe.ts' },
      { id: 'hook:pre-tool', kind: 'hook', name: 'pre-tool', source: 'adapters/claude-code/pre-tool.ts' },
      { id: 'role:coder', kind: 'role', name: 'coder', source: 'skills/coder/SKILL.md' },
      { id: 'role:evaluator', kind: 'role', name: 'evaluator', source: 'skills/evaluator/SKILL.md' },
      { id: 'role:reviewer', kind: 'role', name: 'reviewer', source: 'skills/review/SKILL.md' },
      { id: 'substream:affaan-m/ECC', kind: 'substream', name: 'affaan-m/ECC', source: 'watchlist.yaml' },
      { id: 'skill:coder', kind: 'skill', name: 'coder', source: 'skills/coder/SKILL.md' },
      { id: 'skill:evaluator', kind: 'skill', name: 'evaluator', source: 'skills/evaluator/SKILL.md' },
      { id: 'skill:grill', kind: 'skill', name: 'grill', source: 'skills/grill/SKILL.md' },
      { id: 'skill:review', kind: 'skill', name: 'review', source: 'skills/review/SKILL.md' },
    ]);
  });

  it("lists each self-gate stage as a gate, the name its observations carry (ticket 31)", () => {
    const gates = registryOf({ ...SOURCES, selfGate: ['unit', 'onkel'] }).filter((f) => f.kind === 'gate');
    expect(gates.map((f) => [f.id, f.source])).toEqual([
      ['gate:lint', 'projects/*/project.json checks'],
      ['gate:onkel', 'gates/onkel'],
      ['gate:secret-scan', 'gates/secret-scan'],
      ['gate:self-gate-onkel', 'scripts/self-gate.ts'],
      ['gate:self-gate-unit', 'scripts/self-gate.ts'],
      ['gate:test', 'projects/*/project.json checks'],
    ]);
  });

  it('names the hooks from the hook settings the role sessions run under', () => {
    const settings = { hooks: { PreToolUse: [{ hooks: [{ command: '"node" "/w/adapters/claude-code/pre-tool.ts"' }] }, { hooks: [{ command: '"node" "/w/adapters/claude-code/loop-guard.ts"' }] }], Stop: [{ hooks: [{ command: '"node" "/w/adapters/claude-code/pre-tool.ts"' }] }] } };
    expect(hookScripts(settings)).toEqual(['pre-tool', 'loop-guard']);
    expect(hookScripts({ hooks: { Stop: [{ hooks: [{ command: 'echo done' }, { command: '"node" "/w/adapters/claude-code/stop-gate.ts"' }] }] } })).toEqual(['stop-gate']);
  });

  it('gives each role whose skill exists, by its own name: the planner runs the controller skill, the learner learn, the walker walker', () => {
    const roles = registryOf({ ...SOURCES, skills: ['walker', 'controller', 'learn', 'skeptic'] }).filter((f) => f.kind === 'role');
    expect(roles.map((f) => [f.id, f.source])).toEqual([
      ['role:learner', 'skills/learn/SKILL.md'],
      ['role:planner', 'skills/controller/SKILL.md'],
      ['role:skeptic', 'skills/skeptic/SKILL.md'],
      ['role:walker', 'skills/walker/SKILL.md'],
    ]);
  });
});

describe('parseRegistry and functionsReport', () => {
  const text = registryText(registryOf(SOURCES));

  it('reads back what it wrote', () => {
    expect(parseRegistry(text)).toEqual(registryOf(SOURCES));
    expect(text.endsWith('}\n')).toBe(true);
    expect(JSON.parse(text).$comment).toMatch(/generated by node scripts\/functions\.ts --write/i);
  });

  it.each(['{"functions": [{"id": "gate:a", "kind": "gate", "name": "a", "source": "s"}, null]}', '{', 'null', '{"functions": 3}', '{"functions": [{"id": 1}]}', '{"functions": [{"id": "a", "kind": "gate", "name": "a"}]}', '{"functions": [null]}'])('refuses a registry it cannot read: %s', (bad) => {
    expect(() => parseRegistry(bad)).toThrow(/config\/functions\.json/);
  });

  it('check: 0 when the committed registry is current, 1 with the difference when it is stale or missing', () => {
    expect(functionsReport(text, text, false)).toEqual({ stdout: 'config/functions.json is current: 14 functions.\n', stderr: '', exitCode: 0, write: undefined });
    const stale = registryText(registryOf({ ...SOURCES, hooks: ['pre-tool'] }));
    expect(functionsReport(stale, text, false)).toEqual({
      stdout: '',
      stderr: 'config/functions.json is stale (missing: hook:observe). Run node scripts/functions.ts --write and commit it.\n',
      exitCode: 1,
      write: undefined,
    });
    expect(functionsReport(text, stale, false).stderr).toBe('config/functions.json is stale (not run any more: hook:observe). Run node scripts/functions.ts --write and commit it.\n');
    expect(functionsReport('{', text, false).stderr).toBe('config/functions.json is stale (missing: every function). Run node scripts/functions.ts --write and commit it.\n');
    expect(functionsReport(undefined, text, false).exitCode).toBe(1);
    const both = registryText(registryOf({ ...SOURCES, hooks: ['pre-tool', 'old-hook'], substreams: [] }));
    expect(functionsReport(both, text, false).stderr).toBe(
      'config/functions.json is stale (missing: hook:observe, substream:affaan-m/ECC; not run any more: hook:old-hook). Run node scripts/functions.ts --write and commit it.\n',
    );
    const reordered = text.replace('"source": "gates/onkel"', '"source": "gates/onkel/"');
    expect(functionsReport(reordered, text, false).stderr).toBe('config/functions.json is stale (changed). Run node scripts/functions.ts --write and commit it.\n');
  });

  it('write: the generated text to write, exit 0', () => {
    expect(functionsReport(undefined, text, true)).toEqual({ stdout: 'config/functions.json written: 14 functions.\n', stderr: '', exitCode: 0, write: text });
  });
});
